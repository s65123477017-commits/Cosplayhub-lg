// -----------------------------------------
// ดึงปุ่มแจ้งคืนชุด
// -----------------------------------------

const returnButton =
    document.querySelector(".return-button");


// -----------------------------------------
// ถ้าไม่มีปุ่ม ให้จบการทำงาน
// -----------------------------------------

if (returnButton) {

    returnButton.addEventListener("click", function () {

        // -----------------------------------------
        // ดึง ID รายการจองจาก URL
        // -----------------------------------------

        const urlParams =
            new URLSearchParams(window.location.search);

        const bookingId =
            urlParams.get("id");


        // -----------------------------------------
        // ดึงข้อมูลจาก localStorage
        // -----------------------------------------

        let bookings =
            JSON.parse(
                localStorage.getItem("cosplayHubBookings")
            ) || [];


        const currentUser =
            JSON.parse(
                localStorage.getItem("cosplayHubCurrentUser")
            );


        // -----------------------------------------
        // ตรวจสอบ Login
        // -----------------------------------------

        if (!currentUser) {

            alert(
                "กรุณาเข้าสู่ระบบก่อนแจ้งคืนชุด"
            );

            return;
        }


        // -----------------------------------------
        // ค้นหารายการจอง
        // -----------------------------------------

        const bookingIndex =
            bookings.findIndex(
                booking =>
                    String(booking.id) ===
                    String(bookingId)
            );


        // -----------------------------------------
        // ไม่พบรายการ
        // -----------------------------------------

        if (bookingIndex === -1) {

            alert(
                "ไม่พบข้อมูลรายการจอง"
            );

            return;
        }


        const booking =
            bookings[bookingIndex];


        // -----------------------------------------
        // ตรวจสอบว่าเป็นรายการของผู้ใช้
        // -----------------------------------------

        if (
            booking.customerEmail !==
            currentUser.email
        ) {

            alert(
                "ไม่สามารถแจ้งคืนรายการนี้ได้"
            );

            return;
        }


        // -----------------------------------------
        // ต้องเป็นสถานะกำลังเช่าเท่านั้น
        // -----------------------------------------

        if (booking.status !== "confirmed") {

            if (booking.status === "return_requested") {

                alert(
                    "รายการนี้แจ้งคืนชุดไปแล้ว\n\n" +
                    "กรุณารอร้านตรวจสอบการคืน"
                );

                return;
            }


            if (booking.status === "returned") {

                alert(
                    "รายการนี้คืนชุดเรียบร้อยแล้ว"
                );

                return;
            }


            alert(
                "รายการนี้ยังไม่สามารถแจ้งคืนชุดได้"
            );

            return;
        }


        // -----------------------------------------
        // ยืนยันการแจ้งคืน
        // -----------------------------------------

        const confirmReturn =
            confirm(
                "ยืนยันการแจ้งคืนชุดหรือไม่?\n\n" +
                "หลังจากแจ้งคืนแล้ว ร้านจะตรวจสอบตัวชุด วิก และพร็อพก่อนยืนยันการคืน"
            );


        if (!confirmReturn) {

            return;
        }


        // -----------------------------------------
        // เปลี่ยนสถานะการจอง
        // confirmed
        // ↓
        // return_requested
        // -----------------------------------------

        bookings[bookingIndex] = {
            ...booking,
            status: "return_requested"
        };


        // -----------------------------------------
        // บันทึกข้อมูล
        // -----------------------------------------

        localStorage.setItem(
            "cosplayHubBookings",
            JSON.stringify(bookings)
        );


        // -----------------------------------------
        // แจ้งผล
        // -----------------------------------------

        alert(
            "แจ้งคืนชุดเรียบร้อยแล้ว\n\n" +
            "สถานะ: รอร้านตรวจสอบการคืน"
        );


        // -----------------------------------------
        // โหลดหน้าใหม่
        // เพื่อให้สถานะเปลี่ยนทันที
        // -----------------------------------------

        window.location.reload();

    });

}